"""Word-level karaoke captions as an ASS subtitle file (burned in by libass).

Each caption "page" holds a few words. One dialogue event is emitted per word
so the word being spoken is highlighted (color + pop scale) while the rest of
the page stays visible. Also renders the 2-second on-screen hook text and the
optional commentary banner.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from ..models import CaptionStyle
from .transcribe import Word

_EMOJI = re.compile(
    "[\U00010000-\U0010FFFF☀-➿⬀-⯿️‍⃣]", flags=re.UNICODE
)


def hex_to_ass(color: str, alpha: int = 0) -> str:
    """#RRGGBB -> &HAABBGGRR (ASS colour order is reversed)."""
    color = color.lstrip("#")
    r, g, b = color[0:2], color[2:4], color[4:6]
    return f"&H{alpha:02X}{b}{g}{r}".upper()


def hex_to_ass_override(color: str) -> str:
    color = color.lstrip("#")
    return f"&H{color[4:6]}{color[2:4]}{color[0:2]}&".upper()


def ass_time(seconds: float) -> str:
    cs = int(round(max(seconds, 0.0) * 100))
    h, cs = divmod(cs, 360000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def clean_text(text: str, uppercase: bool = False) -> str:
    text = _EMOJI.sub("", text)
    text = text.replace("\\", "").replace("{", "(").replace("}", ")")
    text = re.sub(r"\s+", " ", text).strip()
    return text.upper() if uppercase else text


def caption_token(text: str, uppercase: bool) -> str:
    token = clean_text(text, uppercase)
    return token.strip(",.;:\"") or token


def group_pages(words: list[Word], max_words: int = 3, max_chars: int = 18, max_gap: float = 0.6) -> list[list[Word]]:
    pages: list[list[Word]] = []
    current: list[Word] = []
    for w in words:
        token = w.text.strip()
        if not token:
            continue
        if current:
            chars = sum(len(x.text.strip()) + 1 for x in current) + len(token)
            gap = w.start - current[-1].end
            sentence_end = current[-1].text.strip()[-1:] in ".?!"
            if len(current) >= max_words or chars > max_chars or gap > max_gap or sentence_end:
                pages.append(current)
                current = []
        current.append(w)
    if current:
        pages.append(current)
    return pages


@dataclass
class Overlay:
    text: str
    start: float
    end: float


def _anchor(style: CaptionStyle, width: int, height: int) -> tuple[int, int, int]:
    x = style.margin_left + (width - style.margin_left - style.margin_right) // 2
    if style.position == "bottom":
        return 2, x, height - style.margin_bottom + style.vertical_offset
    if style.position == "top":
        return 8, x, style.margin_top + 300 + style.vertical_offset
    return 5, x, int(height * 0.60) + style.vertical_offset


def build_ass(
    words: list[Word],
    style: CaptionStyle,
    *,
    width: int = 1080,
    height: int = 1920,
    hook: Overlay | None = None,
    commentary: Overlay | None = None,
) -> str:
    primary = hex_to_ass(style.primary_color)
    outline = hex_to_ass(style.outline_color)
    shadow = hex_to_ass("#000000", 0x60)
    highlight = hex_to_ass_override(style.highlight_color)
    primary_override = hex_to_ass_override(style.primary_color)
    hook_box = hex_to_ass(style.highlight_color)
    banner_box = hex_to_ass("#000000", 0x50)
    font = style.font.replace(",", " ")

    header = f"""[Script Info]
; Generated by ClipPilot
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Caption,{font},{style.font_size},{primary},{primary},{outline},{shadow},-1,0,0,0,100,100,1,0,1,{style.outline:g},{style.shadow:g},5,{style.margin_left},{style.margin_right},0,1
Style: Hook,{font},{int(style.font_size * 0.95)},&H00000000,&H00000000,{hook_box},{shadow},-1,0,0,0,100,100,1,0,3,18,0,8,{style.margin_left},{style.margin_right},{style.margin_top},1
Style: Commentary,{font},{int(style.font_size * 0.6)},&H00FFFFFF,&H00FFFFFF,{banner_box},{shadow},-1,0,0,0,100,100,0,0,3,14,0,8,{style.margin_left},{style.margin_right},{style.margin_top + 170},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events: list[str] = []
    align, x, y = _anchor(style, width, height)
    pos = f"\\an{align}\\pos({x},{y})"
    hs = style.highlight_scale
    pages = group_pages(words, style.max_words, style.max_chars)
    for p_idx, page in enumerate(pages):
        next_start = pages[p_idx + 1][0].start if p_idx + 1 < len(pages) else None
        page_end = page[-1].end + 0.3
        if next_start is not None:
            page_end = min(page_end, next_start) if next_start - page[-1].end > 0.3 else next_start
        page_end = max(page_end, page[-1].end)
        tokens = [caption_token(w.text, style.uppercase) for w in page]
        for i, w in enumerate(page):
            start = w.start if i else page[0].start
            end = page[i + 1].start if i + 1 < len(page) else page_end
            if end - start < 0.04:
                end = start + 0.04
            parts = []
            for j, token in enumerate(tokens):
                if j == i:
                    if style.animation == "pop":
                        small = max(100, int(hs * 0.88))
                        parts.append(
                            f"{{\\1c{highlight}\\fscx{small}\\fscy{small}\\t(0,90,\\fscx{hs}\\fscy{hs})}}{token}"
                            f"{{\\1c{primary_override}\\fscx100\\fscy100}}"
                        )
                    else:
                        parts.append(f"{{\\1c{highlight}}}{token}{{\\1c{primary_override}}}")
                else:
                    parts.append(token)
            text = " ".join(parts)
            events.append(f"Dialogue: 1,{ass_time(start)},{ass_time(end)},Caption,,0,0,0,,{{{pos}}}{text}")

    if hook and hook.text.strip():
        text = clean_text(hook.text, uppercase=True)
        events.append(
            f"Dialogue: 3,{ass_time(hook.start)},{ass_time(hook.end)},Hook,,0,0,0,,"
            f"{{\\fad(80,220)\\fscx80\\fscy80\\t(0,120,\\fscx100\\fscy100)}}{text}"
        )
    if commentary and commentary.text.strip():
        text = clean_text(commentary.text)
        events.append(
            f"Dialogue: 2,{ass_time(commentary.start)},{ass_time(commentary.end)},Commentary,,0,0,0,,"
            f"{{\\fad(200,200)}}{text}"
        )
    return header + "\n".join(events) + "\n"
